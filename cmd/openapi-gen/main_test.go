func TestAnalyzePackageAndRender(t *testing.T) {
	packageName, handlers, err := analyzePackage(options{dir: "testdata/sample", framework: "gin"})
	require.NoError(t, err)
	require.Len(t, handlers, 17)
	assert.Equal(t, "sample", packageName)
	create := findGeneratedHandler(t, handlers, "Create")
	assert.Contains(t, create.request.Properties, "amount")
	assert.Contains(t, create.request.Required, "amount")
	assert.Contains(t, create.response.Properties, "id")
	assert.Equal(t, http.StatusCreated, create.responseStatus)

	createWithHelper := findGeneratedHandler(t, handlers, "CreateWithHelper")
	assert.Contains(t, createWithHelper.request.Properties, "amount")
	assert.Contains(t, createWithHelper.request.Required, "amount")

	getWithHelperResponse := findGeneratedHandler(t, handlers, "GetWithHelperResponse")
	assert.Contains(t, getWithHelperResponse.response.Properties, "id")
	assert.Contains(t, getWithHelperResponse.response.Properties, "active")

	fromStore := findGeneratedHandler(t, handlers, "GetFromStore")
	assert.Contains(t, fromStore.response.Properties, "id")
	assert.NotContains(t, fromStore.response.Description, "Unsupported type")

	deleted := findGeneratedHandler(t, handlers, "Delete")
	assert.Equal(t, http.StatusNoContent, deleted.responseStatus)
	assert.Empty(t, deleted.response)

	generated, err := renderGeneratedFile(packageName, handlers)
	require.NoError(t, err)
	assert.True(t, strings.HasPrefix(string(generated), "// Code generated by openapi-gen. DO NOT EDIT."))
	assert.Contains(t, string(generated), `RegisterGeneratedHandlerSchema("github.com/thiagozs/go-openapi-gen/cmd/openapi-gen/testdata/sample.Handler.Create"`)
}

func TestAnalyzeFormQueryAndContentTypes(t *testing.T) {
	_, handlers, err := analyzePackage(options{dir: "testdata/sample", framework: "gin"})
	require.NoError(t, err)

	login := findGeneratedHandler(t, handlers, "Login")
	assert.Equal(t, "application/x-www-form-urlencoded", login.extras.RequestContentType)
	assert.Contains(t, login.request.Properties, "username")
	assert.Contains(t, login.request.Properties, "remember")
	require.Len(t, login.extras.Parameters, 1)
	assert.Equal(t, "next", login.extras.Parameters[0].Name)
	assert.Equal(t, "query", login.extras.Parameters[0].In)
	assert.Equal(t, "text/html", login.extras.ResponseContentType)

	logout := findGeneratedHandler(t, handlers, "Logout")
	assert.True(t, logout.extras.NoRequestBody)

	report := findGeneratedHandler(t, handlers, "Report")
	assert.Equal(t, "text/markdown", report.extras.ResponseContentType)
	require.Len(t, report.extras.Parameters, 1)
	assert.Equal(t, "false", report.extras.Parameters[0].Schema.Default)

	upload := findGeneratedHandler(t, handlers, "Upload")
	assert.Equal(t, "multipart/form-data", upload.extras.RequestContentType)
	assert.Equal(t, "binary", upload.request.Properties["file"].Format)

	formatResponse := findGeneratedHandler(t, handlers, "FormatResponse")
	assert.Equal(t, http.StatusCreated, formatResponse.responseStatus)
	assert.Equal(t, "string", formatResponse.response.Type)
	assert.Equal(t, "text/html", formatResponse.extras.ResponseContentType)
	assert.Equal(t, http.StatusCreated, formatResponse.extras.ResponseStatus)

	boundUpload := findGeneratedHandler(t, handlers, "BoundUpload")
	assert.Equal(t, "multipart/form-data", boundUpload.extras.RequestContentType)
	assert.Contains(t, boundUpload.request.Properties, "amount")

	for _, name := range []string{"DynamicPostForm", "RawBody", "DirectBody"} {
		handler := findGeneratedHandler(t, handlers, name)
		assert.False(t, handler.extras.NoRequestBody, name)
		assert.True(t, handler.extras.RequestBodyConsumed, name)
	}

	rendered, err := renderGeneratedFile("sample", handlers)
	require.NoError(t, err)
	assert.Regexp(t, `NoRequestBody:\s+true`, string(rendered))
	assert.Regexp(t, `RequestBodyConsumed:\s+true`, string(rendered))
	assert.Regexp(t, `ResponseContentType:\s+"text/markdown"`, string(rendered))
	assert.Regexp(t, `ResponseStatus:\s+201`, string(rendered))
}

